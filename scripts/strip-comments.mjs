/**
 * ═══ نزعُ التعليق قبل كلّ فحصٍ نصّيّ — مصدرٌ واحد ═══
 *
 * **«ظهر الاسمُ ⇒ إذن هو موصول»** هو الشكل الذي خدع البوابات ٥٠ و٥٢
 * و١٩: تعليقٌ يذكر الحقل أو الدالّة باسمها، والفحصُ يقرؤه نداءً.
 * وتعليقاتُ هذا المستودع تُسمّي ما تشرحه في كلّ سطر، فالاحتمالُ
 * الراجح أن يُخدَع لا النادر. **وهو سكوتٌ لا إنذار**، فلا يكشفه أحد.
 *
 * وكان لهذه الدالّة نسختان — في `check-tokens` وفي `model-writers` —
 * **وكلُّ فحصين يقيسان الشيءَ نفسه يقرآن مصدرًا واحدًا**، وإلّا
 * تباعدا والأضعفُ هو الذي يُقرأ.
 *
 * ═══ والأسطر تُحفَظ ═══
 *
 * استبدالُ التعليق بمسافةٍ واحدة يطوي الملفّ بطول التعليق، فيُنذَر
 * على سطرٍ ويُقرأ سطرٌ آخر — فيذهب القارئ إلى سطرٍ سليم ويظنّ
 * الإنذار كاذبًا. فيُفرَّغ الجسدُ ويبقى `\n` مكانه.
 */
export function stripComments(source) {
  const blank = (text) => text.replace(/[^\n]/g, ' ');
  return source
    .replace(/\/\*[\s\S]*?\*\//g, blank)
    .replace(/(^|[^:])(\/\/[^\n]*)/g, (_match, lead, body) => `${lead}${blank(body)}`);
}
