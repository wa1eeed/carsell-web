import { readFileSync } from 'node:fs';

/**
 * ═══ يُستورَد أوّلًا، ويعمل بالاستيراد ═══
 *
 * **والترتيب هو كلُّ شيء.** `src/lib/db` يرمي عند تحميله إن غاب
 * `DATABASE_URL`، فتحميلُ `.env` **بعد** استيراده لا ينفع — والاستيرادات
 * تُقيَّم قبل أيّ سطرٍ تكتبه مهما وضعتَه فوقها. فالتحميل أثرُ وحدةٍ
 * تُستورَد قبلها، لا دالّةٌ تُستدعى.
 *
 * وسقطت `walk:surface` بهذا: تعمل حين يصادف أن تكون البيئة محمَّلة في
 * الصَّدفة، وتسقط حين لا — **وأداةٌ تعمل بالصدفة أسوأ من أداةٍ لا تعمل**،
 * لأن سقوطها يُقرأ على أنه عطلٌ فيما تقيسه.
 *
 * وما في البيئة يفوز على الملفّ: من يُصدّر متغيّرًا يقصده.
 */
for (const line of readFileSync(new URL('../.env', import.meta.url), 'utf8').split('\n')) {
  const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
  const key = match?.[1];
  if (key !== undefined && process.env[key] === undefined) {
    process.env[key] = (match?.[2] ?? '').replace(/^["']|["']$/g, '');
  }
}
