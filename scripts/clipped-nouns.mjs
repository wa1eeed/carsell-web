/**
 * ═══ الأسماءُ المنقوصة — مصدرٌ واحد لقارئيها ═══
 *
 * «جارٍ» تحمل تنوينًا يعوّض ياءً محذوفة، فمسحُ التنوين وحده يُنتج
 * «جار» — كلمةً أخرى. ووقع فعلًا في مسح ٢٠٢٦-١٠-١٨: سبعةٌ وتسعون
 * موضعًا صارت «جار النشر…» و«مشتر نشط» و«{n} ثوان».
 *
 * **والقائمةُ هنا لأنّ قارئيها اثنان**: البوابة ٦١ تحرس المصدر،
 * والماشي على الصفحات يقرأ المُصيَّر. وكان للماشي فئتُه وحده بلا
 * استثناء، فأعلن «تشكيلٌ في نصٍّ معروض» على **ستٍّ وثلاثين صفحة**
 * — خمسٌ وثلاثون منها كلمةُ «مشترٍ» الصحيحة. وخمسةُ مواضعَ حقيقية
 * غرقت بينها: «المكيّف» في تقرير الفحص و«تأخّر» في طابور النزاعات.
 *
 * **وقياسٌ يُنذر كاذبًا يُهمَل**، وهو أسوأ من ألّا يكون.
 */
export const CLIPPED_NOUNS = [
  'جار', 'ثان', 'ثوان',
  'منته', 'مشتر', 'عال',
  'باق', 'كاف', 'ماض', 'راض',
  'متبق', 'قاض', 'محام',
  'داع', 'ناد', 'غال', 'تال',
  'مبن', 'مستوف', 'ملغ',
];

/** الكلمةُ مجرّدةً من التشكيل — أهي منقوصٌ مكتوبٌ بتنوينه؟ */
export function isClippedNoun(word) {
  const bare = word
    .replace(/[ً-ْٰ]/g, '')
    .replace(/^[^ء-ي]+|[^ء-ي]+$/g, '');
  return CLIPPED_NOUNS.includes(bare);
}
