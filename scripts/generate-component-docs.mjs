#!/usr/bin/env node
/**
 * ═══ فهرس المكوّنات — يُولَّد ولا يُكتب ═══
 *
 * `docs/frontend/components.md` سردٌ مكتوبٌ بيد يشرح **لماذا** بُني كل
 * مكوّن، وهو ثمينٌ ويبقى. لكنّه لا يدّعي الإحصاء — وقد قِيس فوُجد
 * **ثمانيةٌ وثلاثون مكوّنًا من واحدٍ وسبعين لا ذكر لها فيه**: نصفُ
 * المكتبة غيرُ مفهرس، وكلُّ مهمةٍ جديدة تزيد الفجوة.
 *
 * ووثيقةٌ تُكتب بيدٍ تصف الشجرة **يوم كُتبت** ثم تُقرأ سنةً وهي تكذب.
 * فالفهرس يُولَّد من الشيفرة: ما فيها هو ما فيه، و`--check` تُسقط
 * البناء إن تباعدا.
 *
 * ═══ وما لا يناديه أحد يُعلَن ═══
 *
 * «مكوّنٌ مبنيٌّ لا يبلغه زرّ» صنفٌ تكرّر في هذا المستودع عشر مرّات.
 * فالفهرس يَعُدّ من يستورد كل مكوّن، ويُفرد عمودًا لمن لا يستورده أحد
 * — فيُرى الميّت في جدولٍ لا يُكتشف بالتصفّح.
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'docs', 'frontend', 'component-index.md');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.tsx?$/.test(entry)) out.push(full);
  }
  return out;
}

/**
 * الرموز المصدَّرة التي تبدأ بحرفٍ كبير — فهي المكوّنات. والأنواع
 * المصدَّرة تُستثنى: `export type Foo` ليست عنصرًا يُرسَم.
 */
function exportedComponents(source) {
  const names = new Set();
  for (const [, name] of source.matchAll(/^export function ([A-Z]\w*)/gm)) names.add(name);
  for (const [, name] of source.matchAll(/^export const ([A-Z]\w*)\s*[:=]/gm)) names.add(name);
  /** و`SETTINGS_HOME` ثابتٌ لا مكوّن — والصارخة تُستبعد بشكلها. */
  return [...names].filter((name) => !/^[A-Z0-9_]+$/.test(name));
}

/** خاصّيّات المكوّن من توقيعه — `{ a, b }: { a: X; b: Y }`. */
function props(source, name) {
  const at = source.indexOf(`function ${name}(`);
  if (at === -1) return [];
  const open = source.indexOf('{', source.indexOf('(', at));
  if (open === -1) return [];
  let depth = 0;
  let end = open;
  for (let i = open; i < source.length && i < open + 4000; i += 1) {
    if (source[i] === '{') depth += 1;
    if (source[i] === '}') {
      depth -= 1;
      if (depth === 0) { end = i; break; }
    }
  }
  const block = source.slice(open + 1, end);
  return [...new Set(
    block
      .split(',')
      .map((part) => part.trim().split(/[:=\s]/)[0])
      .filter((part) => /^[a-z]\w*$/.test(part ?? '')),
  )];
}

/** `'use client'` — والحدّ بين الخادم والعميل يُقرأ من الملفّ لا يُحفظ. */
const isClient = (source) => /^['"]use client['"]/m.test(source);

const files = walk(SRC).filter((file) => file.includes(`${sep}components${sep}`));
const bySource = new Map();
for (const file of files) bySource.set(file, readFileSync(file, 'utf8'));

/** من يستورد ماذا — على كل ملفّ في `src`, لا على المكوّنات وحدها. */
const allSources = walk(SRC).map((file) => readFileSync(file, 'utf8'));

const rows = [];
for (const file of files) {
  const source = bySource.get(file);
  const rel = relative(ROOT, file).split(sep).join('/');
  const names = exportedComponents(source);
  if (names.length === 0) continue;

  for (const name of names) {
    const pattern = new RegExp(`\\b${name}\\b`);
    const users = allSources.filter(
      (other) => other !== source && pattern.test(other),
    ).length;
    rows.push({ name, rel, client: isClient(source), props: props(source, name), users });
  }
}

rows.sort((a, b) => (a.rel === b.rel ? a.name.localeCompare(b.name) : a.rel.localeCompare(b.rel)));

const groups = new Map();
for (const row of rows) {
  const dir = row.rel.replace(/\/[^/]+$/, '');
  if (!groups.has(dir)) groups.set(dir, []);
  groups.get(dir).push(row);
}

const orphans = rows.filter((row) => row.users === 0);

const lines = [
  '# Component index',
  '',
  '**Generated by `npm run docs:generate` — do not edit.**',
  '',
  'Every exported component in `src/components/`, with the file it lives in,',
  'whether it crosses into the client, the props it takes, and how many other',
  'files mention it.',
  '',
  'The narrative — *why* each one exists and what states it must cover — is in',
  '[`components.md`](./components.md). This file only answers "what exists".',
  '',
  `Counted: **${String(rows.length)}** components in **${String(groups.size)}** directories.`,
  '',
];

if (orphans.length > 0) {
  lines.push(
    '## Referenced nowhere else',
    '',
    'A component nothing imports is either dead or about to be. This repo has',
    'closed that class a dozen times; the list is here so it is seen in a table',
    'rather than found by chance.',
    '',
    ...orphans.map((row) => `- \`${row.name}\` — \`${row.rel}\``),
    '',
  );
}

for (const [dir, items] of [...groups.entries()].sort()) {
  lines.push(`## \`${dir}\``, '');
  lines.push('| Component | Client | Props | Referenced in |');
  lines.push('| --- | --- | --- | --- |');
  for (const row of items) {
    const list = row.props.length === 0 ? '—' : row.props.map((p) => `\`${p}\``).join(' · ');
    lines.push(
      `| \`${row.name}\` | ${row.client ? 'yes' : 'no'} | ${list} | ${String(row.users)} |`,
    );
  }
  lines.push('');
}

const next = `${lines.join('\n').trimEnd()}\n`;
const check = process.argv.includes('--check');

if (check) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== next) {
    console.error('✗ docs/frontend/component-index.md قديم — شغّل npm run docs:generate');
    process.exit(1);
  }
  console.log(`✓ فهرس المكوّنات مطابق — ${String(rows.length)} مكوّنًا`);
} else {
  writeFileSync(OUT, next);
  console.log(`✓ ${String(rows.length)} مكوّنًا → docs/frontend/component-index.md`);
}
