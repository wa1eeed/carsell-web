#!/bin/sh
# ═══ الإقلاع: ترحيلٌ ثم تشغيل ═══
#
# **الترحيل يسبق الخادم ويوقفه إن سقط.** حاويةٌ تقلع على مخطّطٍ قديم
# تردّ ٥٠٠ على كل استعلام، والسبب يظهر في السجلّ لا في الشاشة.
# و`migrate deploy` لا يُنشئ ترحيلًا ولا يمسح شيئًا — يطبّق الموجود فقط.
set -e

# ═══ الشروط قبل أيّ شيء ═══
#
# **ثلاثةُ أسرارٍ ترمي عند أوّل استعمالٍ لا عند الإقلاع**: حاويةٌ بلا
# `JWT_SECRET` تُرحّل وتقلع وتردّ `{ok:true}` على الفحص الصحّي — ثم
# تسقط ٥٠٠ على أوّل دخول، والسبب في سجلّ الحاوية لا في الشاشة. فيقول
# المُنسِّق «نُشر» ولا أحد يستطيع الدخول. **والفحص الصحّي يلمس القاعدة
# وحدها، فلا يراها.**
#
# و`CRON_SECRET` غيابُه يُغلق `/api/cron/run` على كل نداء — فلا مزادٌ
# يُغلق ولا طلبٌ غيرُ مدفوعٍ تنقضي مهلتُه، **بلا رسالةٍ واحدة**.
#
# **وتُفحص كلّها فتُطبع كلّها.** التوقّف عند أوّل ناقصٍ يعني دورةَ نشرٍ
# كاملة لكل متغيّر، وهي أسوأ حلقةٍ راجعة ممكنة.
missing=''

require() {
  eval "value=\${$1-}"
  if [ -z "$value" ]; then
    missing="$missing  · $1 — غائب
"
  elif [ "$2" -gt 0 ] && [ "${#value}" -lt "$2" ]; then
    missing="$missing  · $1 — أقصر من $2 محرفًا (الطول ${#value})
"
  fi
}

require DATABASE_URL 0
require JWT_SECRET 32
require OTP_PEPPER 0
require SECRETS_KEY 32
require CRON_SECRET 0

if [ -n "$missing" ]; then
  echo "✗ الإقلاع متوقّف — متغيّراتٌ لازمة ناقصة:"
  printf '%s' "$missing"
  echo "  راجع docs/DEPLOY-STAGING.md القسم ٢."
  exit 1
fi

# و`APP_URL` غيابُه لا يُسقط الإقلاع: الافتراضيّ محلّيّ عمدًا، لكن
# خريطةَ الموقع والروابط المطلقة تشير إلى `localhost` — فيُقال.
if [ -z "${APP_URL-}" ]; then
  echo "⚠ APP_URL غائب — الروابط المطلقة وخريطة الموقع ستشير إلى localhost."
fi

echo "→ تطبيق الترحيلات…"
# **من داخل مجلّد الأداة**: `prisma.config.ts` يستورد `prisma/config`،
# ومن `/app` لا يُحلّ. والمخطّط والإعداد منسوخان إلى جواره.
(cd /opt/prisma && ./node_modules/.bin/prisma migrate deploy)

# ═══ حساب الأدمن من البيئة ═══
#
# **بعد الترحيل وقبل الخادم.** فجدول `AdminUser` موجودٌ حتمًا، واللوحة
# لا تُفتح قبل أن تكون كلمتها هي المكتوبة في لوحة النشر.
#
# ويتخطّى نفسه بلا `ADMIN_EMAIL` — ومن لا يريد هذا الباب لا يُسقط
# إقلاعه. أمّا كلمةٌ ضعيفة أو بريدٌ فاسد فيوقفانه: خادمٌ يعمل ولوحةٌ
# لا تُدخَل عطلٌ يُكتشف متأخّرًا، والفشل هنا في أوّل سطر.
echo "→ مزامنة حساب الأدمن…"
(cd /opt/seed && ./node_modules/.bin/tsx prisma/admin-sync.ts)

echo "→ تشغيل الخادم…"
exec node server.js
