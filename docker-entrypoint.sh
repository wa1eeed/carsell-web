#!/bin/sh
# ═══ الإقلاع: ترحيلٌ ثم تشغيل ═══
#
# **الترحيل يسبق الخادم ويوقفه إن سقط.** حاويةٌ تقلع على مخطّطٍ قديم
# تردّ ٥٠٠ على كل استعلام، والسبب يظهر في السجلّ لا في الشاشة.
# و`migrate deploy` لا يُنشئ ترحيلًا ولا يمسح شيئًا — يطبّق الموجود فقط.
set -e

echo "→ تطبيق الترحيلات…"
# **من داخل مجلّد الأداة**: `prisma.config.ts` يستورد `prisma/config`،
# ومن `/app` لا يُحلّ. والمخطّط والإعداد منسوخان إلى جواره.
(cd /opt/prisma && ./node_modules/.bin/prisma migrate deploy)

# ═══ حساب الأدمن من البيئة ═══
#
# **بعد الترحيل وقبل الخادم.** فجدول `AdminUser` موجودٌ حتمًا، واللوحة
# لا تُفتح قبل أن تكون كلمتها هي المكتوبة في لوحة النشر.
#
# ويتخطّى نفسه بلا `ADMIN_EMAIL` — ومن لا يريد هذا الباب لا يُسقط
# إقلاعه. أمّا كلمةٌ ضعيفة أو بريدٌ فاسد فيوقفانه: خادمٌ يعمل ولوحةٌ
# لا تُدخَل عطلٌ يُكتشف متأخّرًا، والفشل هنا في أوّل سطر.
echo "→ مزامنة حساب الأدمن…"
(cd /opt/seed && ./node_modules/.bin/tsx prisma/admin-sync.ts)

echo "→ تشغيل الخادم…"
exec node server.js
