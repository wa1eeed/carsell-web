#!/bin/sh
# ═══ الإقلاع: ترحيلٌ ثم تشغيل ═══
#
# **الترحيل يسبق الخادم ويوقفه إن سقط.** حاويةٌ تقلع على مخطّطٍ قديم
# تردّ ٥٠٠ على كل استعلام، والسبب يظهر في السجلّ لا في الشاشة.
# و`migrate deploy` لا يُنشئ ترحيلًا ولا يمسح شيئًا — يطبّق الموجود فقط.
set -e

echo "→ تطبيق الترحيلات…"
npx prisma migrate deploy

echo "→ تشغيل الخادم…"
exec node server.js
