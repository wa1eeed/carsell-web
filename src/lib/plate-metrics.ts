/**
 * الفاصل المرسوم بين حروف اللوحة — **ومعه عرضُه**.
 *
 * الحروف تُرسم منفصلةً كما على اللوحة المصنوعة، والفصل بشيئين: مانعُ وصلٍ
 * (`\u200c`) يمنع الحرفين أن يتّصلا، ومسافةٌ تفرّق بينهما للعين.
 *
 * وعرضُه **ليس زينة**: كان الراسم يصل الحروف بهذا الفاصل ويُخبر حاسبَ المقاس
 * أنّ بينها `0.06em` — والمسافة وحدها `0.2778em` في Arial Bold. فكلّ فُرجةٍ
 * تُحسب أقلَّ من حقّها بـ`0.218em`، وثلاثةُ حروفٍ تخرج **أعرض بربعٍ** ممّا
 * قُدِّر لها، فتفيض عن خانتها. وقد فاضت: «سعد» في الاعتيادية تجاوزت حدَّي
 * خانتها بأربع وحداتٍ ونصف من كلّ جهة.
 *
 * فصار الفاصل وعرضُه في موضعٍ واحد: من يصل به يقيس به، ولا يفترقان.
 */
export const ARABIC_SEPARATOR = '\u200c '

/** عرضُ المسافة في Arial Bold — مقيسٌ بـ`measureText`، ومانعُ الوصل صفر. */
export const SPACE_ADVANCE = 0.2778

/** عرضُ الفاصل كلِّه: مانعُ وصلٍ (صفر) ومسافة. */
export const ARABIC_SEPARATOR_ADVANCE = SPACE_ADVANCE

/** مجموع عروض حروف نصٍّ — وما لا يُعرف يأخذ أوسعها فلا يفيض. */
export function arabicAdvance(text: string): number {
  let total = 0
  for (const ch of text) total += ARABIC_LETTER_ADVANCE[ch] ?? 1.0625
  return total
}

