/** أوسع مدى حبر يشغله نصّ — أعلى ارتفاع وأعمق نزول بين محارفه. */
export function inkOf(text: string, table: Record<string, InkMetrics>): InkMetrics {
  let asc = 0
  let desc = -1
  for (const char of Array.from(text)) {
    const metric = table[char]
    if (!metric) continue
    asc = Math.max(asc, metric.asc)
    desc = Math.max(desc, metric.desc)
  }
  // نصّ بلا محارف معروفة: نفترض أوسع الحدود حتى لا يتجاوز الإطار أبدًا
  if (desc === -1) return { asc: 0.876, desc: 0.2119 }
  return { asc, desc }
}

export type RowItem = {
  /** أكبر حجم خط تسمح به المساحة الأفقية */
  widthLimit: number
  ink: InkMetrics
}

export type RowLayout = {
  /** خطّ قاعدة لكل عنصر، بالترتيب نفسه */
  baselines: number[]
  /** حجم الخط النهائي لكل عنصر، بالترتيب نفسه */
  sizes: number[]
}

/**
 * نصيب الحبر من شريطه.
 *
 * الشريط ليس حدًّا يُملأ حتى آخره: للحرف حَولَه فراغٌ في اللوحة المصنوعة. وهذا
 * المقدار مأخوذٌ من الطويلة الخصوصية كما استقرّت — سبعون بالمئة — فتخرج
 * اللوحات كلّها بمقاسٍ واحدٍ إلى شريطها، والشريطُ نسبةٌ من ارتفاع اللوحة.
 */
const INK_FILL = 0.7

/** ارتفاع حبر المحرف نسبةً إلى حجم خطّه — ما فوق القاعدة وما تحتها معًا. */
const inkHeight = (ink: InkMetrics) => Math.max(ink.asc + ink.desc, 0.001)

/**
 * يوزّع عناصر صفّ داخل شريط رأسي: لكلٍّ حجمٌ يجعل حبره بارتفاعٍ واحد، ومَوضعٌ
 * يُوسّطه في الشريط.
 *
 * المقاس يُطلب بالحبر لا بحجم الخطّ. وكان يُطلب بحجم الخطّ فيختلف ما يُرى:
 * حبر اللاتينيّ ‎0.73em‎ وحبر الأرقام العربية ‎0.58em‎، فحجمان متساويان يخرجان
 * ارتفاعين متفاوتين بالرُّبع — ومنه جاء «77» أطول من «٧٧» فوقه في الطويلة،
 * و«1» أطول من «١» في الاعتيادية. وحين يُطلب الحبر يتساوى المرئيّ، ويبقى
 * فرقٌ مقصود: اللاتينيّ أصغر بمعامله لأنّ حروفه أعرض وأثخن فتُقرأ أضخم.
 *
 * ولا قاعدة مشتركة: كلٌّ يُوسَّط في شريطه. القاعدة الواحدة تُساوي المواضع لا
 * المرئيّ — فيعلو ما قصُر صعوده على ما طال، وقد كان «٧٧» يعلو «ر ر» بخمسٍ
 * وعشرين وحدة وهما في صفٍّ واحد.
 *
 * وضيقُ الخانة يحدّ الحجم قبل الشريط، فيخرج الحبر أقصر — وهو حدٌّ لا حيلة فيه.
 */
export function layoutRow(items: RowItem[], bandTop: number, bandHeight: number): RowLayout {
  const target = bandHeight * INK_FILL
  const sizes = items.map((item) => Math.min(item.widthLimit, target / inkHeight(item.ink)))
  const baselines = items.map((item, index) => {
    /** **والفهرسةُ تُفحص**: إعداداتُ هذا المستودع أصرمُ من مصدر النقل. */
    const size = sizes[index] ?? 0
    const above = item.ink.asc * size
    const below = item.ink.desc * size
    return bandTop + (bandHeight - (above + below)) / 2 + above
  })
  return { baselines, sizes }
}

/**
 * أكبرُ حجمِ خطٍّ يَسَع فيه النصُّ خانتَه.
 *
 * و`totalAdvance` **مجموعُ عروض محارفه** لا عددُها مضروبًا في متوسّط: بين
 * «ص» (1.0625) و«ا» (0.2168) خمسةُ أضعاف، فالمتوسّط يُفيض الأولى ويُضيّق
 * الثانية. والمجموع يُصيب كلَّ حالة.
 */
/**
 * هامشُ أمانٍ في المطابقة — **لأنّ الخطّ ليس مضمونًا**.
 *
 * المقاييس في هذا الملفّ مأخوذةٌ من Arial Bold، والخطّ يُطلب من النظام:
 * `Arial, 'Arial Unicode MS', 'Helvetica Neue', sans-serif`. وهو حاضرٌ في
 * macOS وويندوز، **وغائبٌ في لينكس وأندرويد** — فيسقط الرسم إلى بديلٍ
 * مقاييسُه أوسع، فيفيض الحبر عن خانته.
 *
 * وقِيس: «سعد» تقع ١٠٫٨ وحدةً داخل خانتها بـArial، و٢٫١ ببديلٍ عامّ — وفي
 * بوّابة لينكس تجاوزت «نور» خانتها بـ٥٫٥ من ١٥٤.
 *
 * **والمقدار مقيسٌ لا مُخمَّن**: بهامش ٨٪ بقيت «بدر» تتجاوز بـ١٫٦ — أي أنّ
 * البديل يحتاج نحو ١٠٪. فجُعل ١٤٪ ليبقى فضلٌ لتركيباتٍ لم تُقَس ولخطوطٍ
 * أخرى، لا ليُلاحَق أسوأُ ما ظهر في تشغيلةٍ واحدة.
 *
 * **وكلفتُه تقع حيث يلزم وحده.** الحجم النهائيّ `min(حدّ العرض، حدّ الشريط)`،
 * والشريط هو القيد في أكثر اللوحات — فالهامش لا يُغيّر شيئًا فيها. وقِيس على
 * المتصفّح بعد إضافته: «ا» و«رر» و«كطع» و«حد» لم تتغيّر، وتغيّرت «سعد»
 * (‎−١٠٫٨‎ ← ‎−١٦٫١‎) و«وسم» (‎−١٤‎ ← ‎−٢٠٫٩‎) — وهما أضيقُ ما في الصفحة،
 * وهما بعينهما ما كان مهدَّدًا بالفيض.
 *
 * وهذا علاجُ العَرَض. وعلاجُ السبب أن يُشحن خطٌّ مع التطبيق فتُضمن مقاييسه
 * في كلّ منصّة — وهو قرارُ ترخيصٍ وشكلٍ لا يُتّخذ في تصحيحِ عطب.
 */
export const FIT_SAFETY = 0.86

export function fitFontSize(
  totalAdvance: number,
  base: number,
  available: number,
  spacing = 0,
  count = 0,
): number {
  const advance = totalAdvance + spacing * Math.max(count - 1, 0)
  if (advance <= 0) return base
  const natural = base * advance
  const room = available * FIT_SAFETY
  return natural <= room ? base : (room / natural) * base
}
