import { db } from '@/lib/db';

/**
 * ═══ وعدُ «صفر عمولة» يتبع القاعدة النافذة ═══
 *
 * قرار المالك (٢٠٢٦-١٠-١٧): «الوعدُ المكتوب يتغيّر حسب حالة العمولة —
 * إن قمنا بتفعيلها يُزال الوعد».
 *
 * **وكان ثلاثةَ نصوصٍ ثابتة**: «صفر عمولة على كل عملية بيع» في
 * الرئيسية، و«بلا عمولة» في بطاقة البيع، و«صفر عمولة على البيع» في
 * شاشة الدخول. ولا واحدٌ منها يقرأ `CommissionRule` — **بينما صفحةُ
 * المعارض تقرؤها وتعرض النسبة الحيّة**.
 *
 * فتفعيلُ عمولةِ بائعٍ من اللوحة كان يجعل صفحتين من صفحاتك تتناقضان:
 * الرئيسيةُ تَعِد بصفر، وصفحةُ المعارض تقول ٢٫٥٪ — **والقارئ لا يعرف
 * أيَّهما يصدّق**. وهو صنف «النصّ المعروض وعدٌ لا وصف» في أكثر شاشةٍ
 * يصلها الناس.
 *
 * **والوعدُ يُحذف لا يُعدَّل**: «صفر عمولة» إمّا صادقةٌ فتُقال، وإمّا
 * لا فتُرفع. ونصٌّ يقول «عمولتنا ٢٫٥٪» مكانَ وعدٍ كان صفرًا دعايةٌ
 * عكسيّة — والنسبةُ موضعُها صفحةُ المعارض وشاشةُ البيع حيث تُقرأ عند
 * القرار.
 */
export async function sellingIsFree(now: Date = new Date()): Promise<boolean> {
  /**
   * **وأحدثُ قاعدةٍ سارية للبائع** — والتصفيةُ بـ`enabled` بعد
   * الاختيار لا داخله: القواعدُ تُضاف ولا تُعدَّل، فلو صفّى الاستعلام
   * لسقط على أقدمَ مفعَّلة فيعود وعدٌ أُزيل.
   */
  const rule = await db.commissionRule.findFirst({
    where: { scope: 'global', side: 'SELLER', activeFrom: { lte: now } },
    orderBy: { activeFrom: 'desc' },
    select: { enabled: true, pct: true, fixedFee: true },
  });

  if (rule === null || !rule.enabled) return true;
  return Number(rule.pct) === 0 && Number(rule.fixedFee) === 0;
}

/**
 * ═══ أسئلةٌ لا تُعرض حين تُفعَّل العمولة ═══
 *
 * سؤالُ «هل أدفع عمولة على البيع؟» يجيب «صفر بالمئة» نصًّا — **فهو
 * الوعدُ نفسُه في صورة سؤال**. وتفعيلُ العمولة يجعله كذبًا، فيُرفع.
 *
 * **ولا يُعاد كتابتُه تلقائيًّا**: نصُّ الجواب محتوًى يملكه المشغّل
 * من `/admin/faq`، وصياغةُ نصٍّ ضريبيّ بالنيابة عنه ليست من عمل
 * الشيفرة. فيُرفع الوعدُ الكاذب، ويكتب هو جوابَه حين يقرّر نسبته —
 * ولوحةُ الباقات تقول له أيُّ النصوص مرفوعةٌ الآن.
 */
export const PROMISE_FAQ_KEYS: readonly string[] = ['selling_commission'];

/** ما يُستبعَد من الأسئلة المعروضة الآن — وفارغٌ ما دام الوعد صادقًا */
export async function hiddenFaqKeys(now: Date = new Date()): Promise<string[]> {
  return (await sellingIsFree(now)) ? [] : [...PROMISE_FAQ_KEYS];
}
