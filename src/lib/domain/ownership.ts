/**
 * ═══ الشخصيُّ والمنشأةُ — حدٌّ يُكتب مرّة ═══
 *
 * قرار المالك ٢٠٢٦-١١-٢٥: «**صفحة الحساب للمستخدمين، هم أفراد يمكنهم
 * البيع والشراء وليسوا معارض — حيث إن المعارض لهم لوحتهم الخاصة**».
 *
 * وكان العطلُ أنّ `Vehicle` تحمل `ownerId` **و**`dealerId` معًا:
 * فالخمسُ سياراتٍ في مخزون معرض الصفوة ظهرت في كراج صاحبه الشخصيّ
 * **بالصفوف نفسِها**. وأخطرُ ما فيه أنّ للبابين قاعدتين: لوحةُ
 * المعرض تحصر البائع في فرعه (مصفوفة `D9`)، **والكراجُ لا يعرف
 * الفروع أصلًا** — فمخزون المنشأة يُفتح من بابٍ أضعف حراسة.
 *
 * **والحدُّ يُكتب هنا لا في عشر شاشات**: شرطٌ منسوخٌ في عشرة
 * استعلامات يُنسى في الحادي عشر، ولا شيء يشكو — صفٌّ واحد يظهر حيث
 * لا ينبغي ولا إنذارَ له.
 */

/** المركبةُ الشخصية — ما ليس لمنشأة. */
export const PERSONAL_VEHICLE = { dealerId: null } as const;

/** إعلانُ شخصٍ — على مركبةٍ لا معرضَ لها. */
export function personalListingOf(userId: string) {
  return { sellerId: userId, vehicle: PERSONAL_VEHICLE } as const;
}
