import { createHash } from 'node:crypto';

/**
 * ═══ رمزُ الفاحص — هويّةٌ تُطابَق ولا تُعرِّف ═══
 *
 * قرار المالك ٢٠٢٦-١٠-١٨: يُعرض رمزٌ لا اسم. فالتقريرُ يُقرأ على صفحةٍ
 * عامّة، وتسميةُ شخصٍ فحص سيارةَ غريبٍ تُعرّضه لمن لم يُعجبه ما كتب —
 * **والفاحصُ يكتب ما يراه، فلا يُحاسَب عليه وجهًا لوجه**.
 *
 * والرمزُ **مشتقٌّ ثابت** من هويّة من فحص: يتكرّر على تقاريره كلِّها،
 * فمن قرأ تقريرين عرف أنهما لفاحصٍ واحد — وهذا نصفُ فائدته. ولا يُفكّ:
 * لا يُستخرج منه اسمٌ ولا معرّف، والمطابقةُ الداخلية بـ`inspectorName`
 * الباقي في القاعدة.
 *
 * **والأبجديّةُ بلا ملتبسات**: لا صفر ولا حرف O، ولا واحد ولا I — رمزٌ
 * يُملى في هاتفٍ ويُكتب، فحرفٌ يُقرأ رقمًا يُضيّع المطابقة.
 *
 * ═══ وملفُّه وحده بلا `db` ═══
 *
 * تقرؤه البذرةُ باستيرادٍ ساكن، و`inspection.ts` تستورد `db` التي تبني
 * عميل Prisma **وقت تحميل الوحدة** — قبل أن تُحمّل البذرةُ بيئتها. وهي
 * العلّةُ نفسها التي نُقل لأجلها `checkIban` إلى وحدة الآيبان.
 */
const CODE_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

export function inspectorCodeFor(id: string): string {
  const digest = createHash('sha256').update(id).digest();
  let out = '';
  for (let i = 0; i < 4; i += 1) {
    out += CODE_ALPHABET[(digest[i] ?? 0) % CODE_ALPHABET.length];
  }
  return `FA-${out}`;
}
