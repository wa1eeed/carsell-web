/**
 * ═══ نصابُ الموافقة — رقمٌ واحد تقرؤه التدفّقات التسعة ═══
 *
 * **قرار المالك ٢٠٢٦-١٠-١٤**: «موافقة العضوين يجب أن نعمل على إزالة
 * هذا القيد من لوحة الأدمن، حيث الأدمن يملك صلاحية مطلقة».
 *
 * وكان الرقمُ مكتوبًا بيدٍ في ثلاثة ملفّات ومعرَّفًا باسمه في اثنين
 * آخرين بالقيمة نفسها — **خمسُ نسخٍ لقاعدةٍ واحدة**، تتباعد أوّلَ
 * تغيير. فصار مصدرًا واحدًا: من أراد إعادة العضوين بدّل سطرًا.
 *
 * **والطالبُ هو النصاب حين يكون النصاب واحدًا.** فطلبٌ استوفى نصابَه
 * يُنفَّذ في النداء نفسِه، ولا يُترك صفًّا معلَّقًا ينتظر الشخصَ نفسَه
 * ليضغط ثانيةً — وهو «عضوان عضوًا يضغط مرّتين» الذي سخر منه تعليقُ
 * الشيفرة نفسُه.
 */
export const REQUIRED_APPROVALS = 1;

/**
 * أيُمنع الطالبُ من الموافقة على طلبه؟
 *
 * **يُمنع ما دام النصاب أكثر من واحد** — فرفعُه إلى اثنين يُعيد السلوك
 * القديم بلا تعديلٍ آخر، ولا يبقى في الشيفرة فحصٌ يناقض الرقم.
 */
export function selfApprovalBlocked(
  request: { requestedBy: string; requiredApprovals: number },
  adminId: string,
): boolean {
  return request.requiredApprovals > 1 && request.requestedBy === adminId;
}

/** هل يكفي الطالبُ وحده؟ — يقرؤها كلُّ `request*` ليُنفّذ في نداءٍ واحد. */
export const soloQuorum = (): boolean => REQUIRED_APPROVALS <= 1;
