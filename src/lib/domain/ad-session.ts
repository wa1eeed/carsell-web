/**
 * ═══ سقفُ إعلانات الجلسة — ويُفرَض في الخادم ═══
 *
 * ترميز A30 يكتبها بنصّها: «٤ إعلانات كحدّ أقصى في جلسة الرئيسية،
 * **والسقف يُفرَض في الخادم لا في التطبيق**». والسببُ أنّ سقفًا في
 * العميل ليس سقفًا: يُتجاوَز بإعادة تحميل، وبنسخةٍ معدَّلة من التطبيق،
 * وبطلبٍ مباشر — وهو الدرس المسجَّل في هذا المستودع مرارًا.
 *
 * وكان `HOME_SESSION_AD_CAP` ثابتًا **لا يقرؤه أحد**، وبطاقةُ A30
 * تقول «قاعدة — ولا إعلان في الرئيسية بعد». **والرئيسيةُ تعرض
 * إعلانين**: `home_banner` و`brand_featured` مبنيّان ويُصيَّران.
 *
 * ═══ والعدُّ على ما ظهر لا على ما طُلب ═══
 *
 * صفحةٌ صُيِّرت وما نزل إليها أحد ليست ظهورًا — وهي القاعدة نفسُها
 * التي بُني عليها مسارُ الظهور (`cpm` يُباع بالظهور لا بالتصيير). فما
 * يزيد العدّاد هو الظهور المؤكَّد، لا فتحُ الصفحة.
 *
 * ═══ وهذا الملفّ بلا `db` ═══
 *
 * يقرؤه الوسيط (يعمل على الحافة)، والصفحة، ومسار الظهور. واستيرادُ
 * وحدةٍ تلمس Prisma في الوسيط يُسقط البناء.
 */

/** ٤ إعلانات كحدّ أقصى في جلسة الرئيسية — كما في الترميز. */
export const HOME_SESSION_AD_CAP = 4;

/**
 * كوكي الجلسة — **بلا `maxAge`**، فينتهي بإغلاق المتصفّح.
 *
 * و«الجلسة» في الترميز جلسةُ تصفّحٍ لا يوم: سقفٌ يوميّ يجعل من يفتح
 * الموقع عشر مرّات في اليوم يرى إعلانًا واحدًا في التاسعة، وسقفُ
 * الجلسة يُعيد له أربعةً في كلّ زيارة.
 */
export const AD_SESSION_COOKIE = 'carz_ads';

/** الرأسُ الذي يمرّره الوسيط إلى الصفحة — عددُ ما بقي من السقف. */
export const AD_ALLOWANCE_HEADER = 'x-home-ads';

/**
 * المساحاتُ التي يحكمها سقفُ الرئيسية.
 *
 * **وليست كلَّ المساحات**: الترميز يقول «جلسة الرئيسية» بنصّه، وبطاقةُ
 * المموّل في النتائج والبنر داخل صفحة السيارة لهما موضعُهما وسقفُهما
 * (`maxPerSession` لكلّ مساحة). وتعميمُ سقف الرئيسية عليها يُسكت
 * إعلانًا بيع بشروطٍ أخرى.
 */
export const HOME_SLOTS: readonly string[] = ['home_story', 'home_banner', 'brand_featured'];

/**
 * ما ظهر في هذه الجلسة — **وقيمةٌ فاسدة تُقرأ صفرًا لا ترمي**.
 *
 * الكوكي يكتبه الخادم، لكنّ العميل يملك تعديله: عددٌ سالب أو نصٌّ أو
 * رقمٌ خياليّ كلُّه وارد. فيُحدّ من الطرفين — والسالب صفرٌ، وما فوق
 * السقف سقفٌ.
 */
export function seenAds(raw: string | undefined): number {
  if (raw === undefined) return 0;
  const parsed = Number.parseInt(raw, 10);
  if (!Number.isFinite(parsed) || parsed < 0) return 0;
  return Math.min(parsed, HOME_SESSION_AD_CAP);
}

/** كم إعلانًا يجوز عرضُه الآن — صفرٌ حين بلغ السقف. */
export function remainingHomeAds(raw: string | undefined): number {
  return Math.max(0, HOME_SESSION_AD_CAP - seenAds(raw));
}

/** قيمةُ الكوكي بعد ظهورٍ واحد — ولا تتجاوز السقف. */
export function afterImpression(raw: string | undefined): string {
  return String(Math.min(HOME_SESSION_AD_CAP, seenAds(raw) + 1));
}

/**
 * ما تقوله الصفحة للخادم — **والرأسُ يُقرأ بحدوده**.
 *
 * الرأسُ يضعه الوسيط، لكنّ الصفحة تقرؤه من طلبٍ قد يصلها بلا وسيط
 * (تصييرٌ ساكن، أو مسارٌ خارج `matcher`). فغيابُه يعني «لا سقف
 * محسوب» — والأسلمُ حينها الأصغر: صفرٌ يُسكت إعلانًا بيع، والسقفُ
 * الكامل يُعطي أكثر ممّا بيع. فيُعطى السقفُ الكامل ويُفرَض العدُّ عند
 * الظهور، فهو الموضع الذي لا يُتجاوَز.
 */
export function allowanceFromHeader(raw: string | null): number {
  if (raw === null) return HOME_SESSION_AD_CAP;
  const parsed = Number.parseInt(raw, 10);
  if (!Number.isFinite(parsed) || parsed < 0) return 0;
  return Math.min(parsed, HOME_SESSION_AD_CAP);
}
