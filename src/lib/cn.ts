/**
 * ═══ ضمُّ أصناف CSS — **ولا يدمجها** ═══
 *
 * **والتعليقُ هنا كان يكذب.** قال «آخر صنف يفوز كما في CSS»، وهو غيرُ
 * صحيح: الدالّة تصفّ النصوص، ومن يقرّر الفائزَ بين صنفين يضبطان
 * الخاصّية نفسَها هو **ترتيبُ تيلويند في ملفّه المولَّد** لا ترتيبُ
 * النصّ هنا. وقِيس في المتصفّح: `inline-flex hidden` و`hidden
 * inline-flex` كلتاهما تُنتجان `inline-flex` — فـ`hidden` لا تُخفي
 * زرًّا أساسُه `inline-flex` مهما كُتبت.
 *
 * وقد أخفى ذلك إخفاءَ «بع سيارتك» على الهاتف، وقبله مقاسَ الشعار في
 * الترويسة.
 *
 * ═══ ولا مكتبةَ دمج — بقياس ═══
 *
 * `tailwind-merge` يُصلحها كلَّها ويضيف تبعيّة. وقِيس المُصيَّر على
 * ثماني صفحات (٢٠٧٣ عنصرًا): **تسعةُ تصادماتٍ حقيقية بشكلين**، أحدهما
 * يُحسم لصالح المُنادي صدفةً (`px-9` تغلب `px-4.5`) والآخر هو العطل
 * أعلاه. فتسعةٌ لا تشتري تبعيّة.
 *
 * **والخيارُ الثالث قياسٌ دائم**: الماشي على الصفحات يعدّ التصادمات
 * في كل زحفة، فلا تنمو صامتةً — وإن نمت عاد السؤال ومعه رقمُه.
 *
 * فمن أراد غَلَبَ صنفٍ على أساسِ مكوّنٍ **يضعه على غلافٍ** لا على
 * المكوّن: الغلافُ بلا أساسٍ يغالبه.
 */
export function cn(
  ...values: readonly (string | false | null | undefined)[]
): string {
  return values.filter((v): v is string => typeof v === 'string' && v !== '').join(' ');
}
