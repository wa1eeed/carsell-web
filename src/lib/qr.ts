import QRCode from 'qrcode';

/**
 * ═══ رمزُ الاستجابة السريعة — يُرسم على الخادم ═══
 *
 * **وSVG لا PNG**: التقريرُ يُطبع ورقًا، ورمزٌ نقطيّ بعرضٍ ثابت يتشقّق
 * على ٣٠٠ نقطة في البوصة فلا تقرؤه كاميرا. والمتّجهُ يطبع بدقّة
 * الطابعة أيًّا كانت.
 *
 * **وعلى الخادم لا في المتصفّح**: حزمةُ الترميز ٣٠ كيلوبايت، وتحميلُها
 * في كل صفحةِ تقريرٍ ثمنٌ يدفعه قارئٌ لن يمسح الرمز غالبًا. والصفحةُ
 * تصل مرسومةً.
 *
 * **ومستوى التصحيح `M`**: يحتمل ربعَ الرمز تالفًا — وهو حدٌّ معقول
 * لورقةٍ تُطوى وتُصوَّر. و`H` يُكبّر الرمز بلا داعٍ على رابطٍ قصير.
 */
export async function qrSvg(payload: string, size = 96): Promise<string> {
  return QRCode.toString(payload, {
    type: 'svg',
    errorCorrectionLevel: 'M',
    margin: 0,
    width: size,
    color: { dark: '#1a1a18', light: '#00000000' },
  });
}
