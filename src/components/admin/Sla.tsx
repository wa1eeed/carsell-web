import { Quantity } from '@/components/ui/Quantity';

/**
 * ═══ التزامُ المزوّد — وكان دالّتين متطابقتين ═══
 *
 * كُتبت مرّتين حرفًا بحرف: في جدول المزوّدين وفي صفحة طلب الخدمة.
 * ونسختان تتباعدان أوّل تغيير، **وقد تباعدتا في صياغتهما أصلًا** —
 * كلتاهما تكتب «ساعات (٤٨)»، وهو التفافٌ على بوابة الجمع يُقرأ أنّ
 * النصّ آليّ (البوابة ٤١).
 *
 * ═══ والساعاتُ حتى يومين — بقرار التصميم ═══
 *
 * «أيّام (٢)» لالتزامٍ مدّتُه ٤٨ ساعة أبعد عن القارئ من «٤٨ ساعة»،
 * وهي المدّة التي يقولها العقد. فالحدُّ ٧٢ ساعة لا ٢٤، و`<Duration>`
 * تنتقل إلى الأيّام عند ٢٤ — فالقاعدة هنا لا فيها.
 *
 * **والصفرُ «فوريّ» لا «لا ساعات»**: التزامٌ بلا مهلةٍ وعدٌ لا نفي.
 */
export function Sla({ hours }: { hours: number | null }) {
  if (hours === null) return <span>بلا التزام</span>;
  if (hours === 0) return <span>فوري</span>;
  if (hours < 72) return <Quantity unit="hours" count={hours} />;
  return <Quantity unit="days" count={Math.round(hours / 24)} />;
}
