-- ═══ شعاراتُ الماركات تصل البيئةَ القائمة ═══
--
-- **والبذرةُ لا تصل بيئةً تعمل**: تمرّ مرّةً على قاعدةٍ فارغة، وشاشاتُ
-- الأدمن تعدّل ولا تُعيد الزرع. فصفٌّ يُضاف إلى البذرة يصل بيئةً
-- جديدة ولا يصل بيئةً تعمل — وهي القاعدة نفسها التي أُضيفت لأجلها
-- ترحيلاتُ قوالب الإشعار والتشكيل.
--
-- وقِيس قبل هذا الترحيل: **٤٢ ماركة و‌صفرُ شعارات**.
--
-- **ولا يُلمس ما رفعه المشغّل**: `WHERE "logoUrl" IS NULL` — فشعارٌ
-- حقيقيٌّ رُفع من اللوحة يبقى، والفارغُ وحده يأخذ الشارة.
UPDATE "Brand"
   SET "logoUrl" = '/brand-logos/' || "slug" || '.svg'
 WHERE "logoUrl" IS NULL OR "logoUrl" = '';
