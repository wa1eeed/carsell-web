-- كانت كلُّها ١، أي أنّ كلّ قسمٍ سدسُ الدرجة مهما كان عددُ بنوده
-- وأيًّا كان ما يُكلّف إصلاحه. وأثرُه:
--
--   الإطارات كلُّها فاسدة (١٥ بندًا)  ⇒  ٨٣
--   الهيكل والصبغ كلُّه فاسد (٤٠ بندًا) ⇒  ٨٣
--
-- **والإطاراتُ تُبدَّل بثلاثة آلاف، والهيكلُ المعوجّ هو سببُ ألّا
-- تشتريها أصلًا** — والرقمان متساويان. والشارةُ الحرجة تسقف التقدير
-- عند «مقبول» لكنّ الرقم يبقى ٨٣.
--
-- والمعيار المُقرّ: **كلفةُ الإصلاح وأثرُه على القرار**. ما لا يُصلَح
-- يثقل، وما يُشترى من أيّ محلّ يخفّ.
--
-- **و`weight = 1` في الشرط**: من بدّل وزنًا من اللوحة لا نكتب فوقه.
-- والتقاريرُ الصادرة لا تتغيّر: لقطتُها محفوظةٌ فيها.
