-- ═══ «معاينة» لم تكن خدمةَ مزوّدٍ قطّ ═══
--
-- صفٌّ في `Service` بسعر صفرٍ و`providerType = NULL`، فـ`cityPool`
-- تُعيد فراغًا و`requestService` تردّ `CITY_NOT_COVERED` **دائمًا**.
-- وزرُّها في صفحة المركبة يقول «قريبًا» — وعدٌ لم يقع.
--
-- وقرار المالك (٢٠٢٦-١٠-١٧): «افعل ما تراه احترافيًّا ويناسب السوق
-- السعودي». **والمعاينةُ لقاءٌ بين مشترٍ وبائع**: لا طرفَ ثالثًا
-- يؤدّيها ولا مالَ فيها ولا مزوّدَ لها. فصار لها كيانُها (`Viewing`)
-- وأُطفئ الصفّ.
--
-- **ولا يُحذف**: `ServiceRequest.serviceId` يرجع إليه بـ`Restrict`،
-- وحذفُه يُسقط تاريخَ ما طُلب. يُطفأ ويُرفع عن السطوح.
UPDATE "Service"
   SET "active" = false, "placements" = '{}'
 WHERE "key" = 'viewing';
