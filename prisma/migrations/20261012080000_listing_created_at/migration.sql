-- متى أُنشئ الإعلان — ولم يكن يُسجَّل.
--
-- `Listing` بلا `createdAt` منذ المخطّط الأوّل، والتعليق فيه يقوله:
-- «فالانتظار لا يُقاس بدونه». وصفحةُ تاريخ الإعلان تبدأ من النشر —
-- فما قبله (كم مكث مسودّةً؟ متى بدأ صاحبُه؟) لا يُعرف.
--
-- ═══ والصفوف القائمة تبقى فارغة ═══
--
-- `ADD COLUMN ... DEFAULT now()` يملأ كل صفٍّ قديم بلحظة الترحيل —
-- فيقول عن إعلانٍ من أغسطس إنه أُنشئ اليوم. **وتاريخٌ مخترَع في
-- شاشة تحقيق أسوأ من تاريخٍ غائب.**
--
-- فالعمود يُضاف بلا افتراضيّ (القديم `NULL` = لا نعرف)، ثمّ يُضبط
-- الافتراضيّ للجديد وحده.
ALTER TABLE "Listing" ADD COLUMN IF NOT EXISTS "createdAt" TIMESTAMP(3);
ALTER TABLE "Listing" ALTER COLUMN "createdAt" SET DEFAULT CURRENT_TIMESTAMP;
