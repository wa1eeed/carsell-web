-- ═══ والنقضُ يحذف ما نقلَه هذا الترحيل وحده ═══
--
-- لا يلمس الترحيلُ "Order" ولا يكتب فيه شيئًا — يقرؤه ليشتقّ منه
-- وقائعَ بيعٍ لم تكن مسجَّلة. فالنقضُ حذفُ تلك الوقائع.
--
-- وحدُّها زمنيّ لا وصفيّ: كلُّ واقعةٍ منقولة بيعتُها **قبل** هذا
-- الترحيل، وكلُّ ما يكتبه المنتجُ بعده بيعتُه بعده. ووصفٌ كـ«بلا
-- مندوب» يطابق أيضًا شراءً مباشرًا جديدًا لم يفاوض فيه أحد — فيحذف
-- النقضُ وقائعَ حقيقية.
DELETE FROM "DealerSale"
WHERE "channel" = 'MARKET'
  AND "orderId" IS NOT NULL
  AND "soldAt" < TIMESTAMP '2026-11-27 00:00:00';
