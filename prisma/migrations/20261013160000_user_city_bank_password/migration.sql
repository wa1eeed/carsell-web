-- مدينةُ الحساب واسمُ مصرفه وكلمةُ مروره.
--
-- ═══ والمدينة تُسأل عند التسجيل ═══
--
-- وكانت تُستنتج من الإعلان: من لم ينشر شيئًا لا مدينة له، فلا تُرشَّح
-- له نتيجة ولا يُعرف أين يُستلم منه.
--
-- ═══ واسمُ المصرف مع الآيبان ═══
--
-- الآيبان وحده لا يكفي كشفَ تحويلٍ يُراجَع بيد: من يطابق الكشف يقرأ
-- اسمًا لا أربعًا وعشرين خانة.
--
-- ═══ وكلمةُ المرور اختيارية ═══
--
-- تسعةٌ وعشرون حسابًا قائمًا سُجّلت برقمٍ ورمزٍ لمرّة واحدة، ولا كلمة
-- لها. فعمودٌ إلزاميّ يُغلق عليها حساباتها — والاختياريّ يترك الرمز
-- بابًا قائمًا لمن لم يضع كلمة.
