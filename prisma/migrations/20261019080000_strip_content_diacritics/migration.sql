-- ═══ تتمّةُ مسح التشكيل — ما لم يبلغه المسحُ الأوّل ═══
--
-- `20261018200000_strip_diacritics` مسح تسعة جداول، **وبقيت أربعة**:
-- أسماءُ التكاملات وسلوكُها عند العطل، ونصُّ قوالب السيو الذي يُطبع
-- في **صفحات الهبوط العامّة**، وموضعُ المساحة الإعلانية، وأسماءُ
-- بنود الفحص في عمود `nameEn`.
--
-- ولم يُكتشف إلّا بالمشي: البوابة ٦١ تقرأ `src/` و`seed-data/*.json`
-- **ولا تقرأ `prisma/migrations/*.sql`** — وقالبُ الفحص كلُّه زُرع
-- بترحيلٍ لا بملفّ بذرة، فمرّ من تحتها. (وُسّعت البوابة في الالتزام
-- نفسه فلا يعود.)
--
-- ═══ والمرجعيُّ وحده يُمسح — والسجلّاتُ لا ═══
--
-- وصفُ البائع لسيارته، وملاحظةُ المشتري على موعدٍ، وسببُ نزاعٍ أو
-- بلاغ، واسمُ مزوّد: **كلماتٌ قالها صاحبُها**. وتعديلُها تزويرٌ لا
-- تنسيق — وهي القاعدة نفسُها التي التزمها المسحُ الأوّل.
--
-- ولونُ المركبة مثلُها: حقلٌ يكتبه البائع بيده. وما في قاعدة التطوير
-- منه («فضّي») صفوفٌ زُرعت قبل المسح، و`prisma/seed.ts` نظيفٌ اليوم
-- فلا يعود في زرعٍ جديد.
--
-- والفئةُ بمهاربها لا بحروفها، وإلّا أبطلها المسحُ التالي.

UPDATE "Integration" SET
  "nameAr"          = regexp_replace("nameAr",          E'[\\u064B-\\u0652\\u0670]', '', 'g'),
  "failureBehavior" = regexp_replace("failureBehavior", E'[\\u064B-\\u0652\\u0670]', '', 'g');

UPDATE "SeoTemplate" SET
  "titleAr" = regexp_replace("titleAr", E'[\\u064B-\\u0652\\u0670]', '', 'g'),
  "introAr" = regexp_replace("introAr", E'[\\u064B-\\u0652\\u0670]', '', 'g'),
  "outroAr" = regexp_replace("outroAr", E'[\\u064B-\\u0652\\u0670]', '', 'g');

UPDATE "AdSlot" SET
  "nameAr"    = regexp_replace("nameAr",    E'[\\u064B-\\u0652\\u0670]', '', 'g'),
  "placement" = regexp_replace("placement", E'[\\u064B-\\u0652\\u0670]', '', 'g');

-- و`nameEn` في بنود الفحص يحمل عربيًّا — زرعَه الترحيلُ في العمودين
-- معًا. والمسحُ هنا يُصلح العرض؛ وترجمتُه مهمّةٌ أخرى مسجَّلة.
UPDATE "InspectionItem" SET
  "nameAr" = regexp_replace("nameAr", E'[\\u064B-\\u0652\\u0670]', '', 'g'),
  "nameEn" = regexp_replace("nameEn", E'[\\u064B-\\u0652\\u0670]', '', 'g');

