-- ═══ حالُ «صبغ» يصير حالًا يكتبها الفاحص ═══
--
-- قرار المالك ٢٠٢٦-١٠-١٨: تبقى «صبغ» وتُدار من بند الهيكل. وكانت حالًا
-- في العرض وحده — البذرة تكتبها ولا نموذجَ فاحصٍ يُنتجها.
ALTER TYPE "InspectionResultState" ADD VALUE IF NOT EXISTS 'REPAINT';

-- ═══ واسمُ القسم يصير «الهيكل الخارجي» ═══
--
-- **والبياناتُ المرجعية تصل القاعدةَ الحيّة بترحيل لا ببذرة**: ملفّ
-- البذرة يُطبَّق على قاعدةٍ فارغة مرّةً واحدة، وشاشةُ القالب تعدّل ولا
-- تُنشئ — فتسميةٌ تُغيَّر في الملفّ تصل بيئةً جديدة ولا تصل بيئةً تعمل.
--
-- و`key` ثابتٌ لا يُمسّ: به تُطابَق اللقطةُ المجمَّدة بالقالب الجديد،
-- فتقريرٌ صدر أمس يبقى مقروءًا.
UPDATE "InspectionCategory"
SET "nameAr" = 'الهيكل الخارجي', "nameEn" = 'Exterior body'
WHERE "key" = 'body';
