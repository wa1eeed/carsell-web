-- ═══ شارةٌ على بطاقة السيارة — وموضعٌ كان بلا قارئ ═══
--
-- `card_badge` معرَّفٌ منذ A19 ويُضبط من لوحة الأدمن **ولا يقرؤه شيء**:
-- لا بطاقة في المنتج كلِّه تعرض ميزةً. (طلب المالك ٢٠٢٦-١٠-١٨.)
--
-- وخمسٌ تُشعَل بدءًا — والمشغّل يبدّلها من `/admin/catalog/features` بلا
-- نشر. والاختيار على ما يُفرّق في السوق السعودي لا على ما يَعمّ: المكيّف
-- الأوتوماتيك في كل سيارة، والمقاعد المبرّدة ليست كذلك.
--
-- **وشارةٌ على كل بطاقة ليست شارة** — فالبطاقة تعرض اثنتين على الأكثر.
UPDATE "Feature"
SET "placements" = array_append("placements", 'card_badge')
WHERE "key" IN (
  'ventilated_seats',  -- مقاعد مبردة: حرُّ الخليج يجعلها مطلبًا لا ترفًا
  'sunroof',           -- فتحة سقف
  'panoramic_roof',    -- سقف بانورامي
  'camera_360',        -- كاميرا محيطية ٣٦٠°
  'adaptive_cruise'    -- مثبت سرعة تكيفي
)
  AND NOT ('card_badge' = ANY("placements"));
