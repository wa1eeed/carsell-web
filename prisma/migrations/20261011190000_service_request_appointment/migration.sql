-- موعدُ الخدمة وموقعها — **يُجمعان من المستخدم ويُهملان**.
--
-- استمارة طلب الخدمة تسأل عن المدينة والموعد وترسلهما، ثمّ:
--   · المدينة تُفحص مقابل تغطية المزوّد **ثمّ تُرمى**،
--   · والموعد يُكتب في `dueAt` — وهو مهلةُ المزوّد لا موعدُ العميل.
--
-- فالصفّ المحفوظ لا يقول أين يذهب الفاحص ولا متى. والمزوّد يُرسَل إلى
-- طلبٍ بلا عنوان، والعميل يفتح «تقاريري» فلا يجد موعده الذي اختاره.
--
-- والتصميم (Wx) يعرض الاثنين في لوحة الطلب قبل زرّ الدفع: «موقع
-- البائع — حي الملقا، الرياض» و«الاثنين ١٧ · ٥:٠٠ م».
--
-- وكلاهما اختياريّ: خدمةٌ بلا موعدٍ مختار تبقى كما كانت.
ALTER TABLE "ServiceRequest" ADD COLUMN IF NOT EXISTS "scheduledAt" TIMESTAMP(3);
ALTER TABLE "ServiceRequest" ADD COLUMN IF NOT EXISTS "city" TEXT;

-- وفهرسٌ على الموعد: شاشة المزوّد تُرتَّب به، ولا تُقرأ بالمهلة.
CREATE INDEX IF NOT EXISTS "ServiceRequest_scheduledAt_idx" ON "ServiceRequest"("scheduledAt");
